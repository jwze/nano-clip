import XCTest
@testable import NanoClipCore

final class CaptureRulesTests: XCTestCase {
    func testPlainTextIsCaptured() {
        let snapshot = PasteboardSnapshot(types: ["public.utf8-plain-text"], string: "hello")
        XCTAssertEqual(CaptureRules.decide(snapshot), .text(text: "hello", truncated: false))
    }

    func testWhitespaceOnlyTextIsSkipped() {
        let snapshot = PasteboardSnapshot(types: ["public.utf8-plain-text"], string: " \n\t\n ")
        XCTAssertEqual(CaptureRules.decide(snapshot), .skip(.empty))
    }

    func testFileOnlyCopyIsSkipped() {
        let snapshot = PasteboardSnapshot(
            types: ["public.file-url", "NSFilenamesPboardType"],
            string: nil
        )
        XCTAssertEqual(CaptureRules.decide(snapshot), .skip(.filesOnly))
    }

    func testFileCopyNeverProducesATextEntry() {
        // Finder can advertise a plain string alongside a file URL; files must still be ignored.
        let snapshot = PasteboardSnapshot(
            types: ["public.file-url", "NSFilenamesPboardType"],
            string: "/Users/someone/report.pdf"
        )
        XCTAssertEqual(CaptureRules.decide(snapshot), .text(text: "/Users/someone/report.pdf", truncated: false))

        let noString = PasteboardSnapshot(types: ["public.file-url"], string: nil)
        XCTAssertEqual(CaptureRules.decide(noString), .skip(.filesOnly))
    }

    func testConcealedContentIsSkipped() {
        let snapshot = PasteboardSnapshot(
            types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"],
            string: "hunter2"
        )
        XCTAssertEqual(CaptureRules.decide(snapshot), .skip(.concealed))
    }

    func testTransientAndAutoGeneratedAreSkipped() {
        XCTAssertEqual(
            CaptureRules.decide(PasteboardSnapshot(
                types: ["public.utf8-plain-text", "org.nspasteboard.TransientType"],
                string: "x"
            )),
            .skip(.transient)
        )
        XCTAssertEqual(
            CaptureRules.decide(PasteboardSnapshot(
                types: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"],
                string: "x"
            )),
            .skip(.autoGenerated)
        )
    }

    func testRemoteClipboardIsSkipped() {
        let snapshot = PasteboardSnapshot(
            types: ["public.utf8-plain-text", "com.apple.is-remote-clipboard"],
            string: "from iphone"
        )
        XCTAssertEqual(CaptureRules.decide(snapshot), .skip(.remoteClipboard))
    }

    func testImageSnapshotIsCaptured() {
        let snapshot = PasteboardSnapshot(types: ["public.tiff"], tiff: Data([0x01, 0x02]))
        XCTAssertEqual(CaptureRules.decide(snapshot), .image)
    }

    func testTextWinsOverImage() {
        let snapshot = PasteboardSnapshot(
            types: ["public.tiff", "public.utf8-plain-text"],
            string: "caption",
            tiff: Data([0x01])
        )
        XCTAssertEqual(CaptureRules.decide(snapshot), .text(text: "caption", truncated: false))
    }

    func testUnsupportedPayloadIsSkipped() {
        let snapshot = PasteboardSnapshot(types: ["com.example.custom"], string: nil)
        XCTAssertEqual(CaptureRules.decide(snapshot), .skip(.unsupported))
    }

    func testLongTextIsTruncatedAndFlagged() {
        let long = String(repeating: "a", count: TextNormalizer.maxLength + 10)
        guard case .text(let text, let truncated) = CaptureRules.decide(
            PasteboardSnapshot(types: ["public.utf8-plain-text"], string: long)
        ) else {
            return XCTFail("expected text decision")
        }
        XCTAssertTrue(truncated)
        XCTAssertEqual(text.count, TextNormalizer.maxLength)
    }
}

final class TextNormalizerTests: XCTestCase {
    func testNormalizesWindowsNewlines() {
        XCTAssertEqual(TextNormalizer.normalize("a\r\nb\rc")?.text, "a\nb\nc")
    }

    func testTrimsTrailingWhitespaceAndEdgeNewlines() {
        XCTAssertEqual(TextNormalizer.normalize("\n\nhello  \n\n")?.text, "hello")
    }

    func testKeepsLeadingIndentation() {
        XCTAssertEqual(TextNormalizer.normalize("    indented code\n")?.text, "    indented code")
    }

    func testEmptyAndWhitespaceOnlyReturnNil() {
        XCTAssertNil(TextNormalizer.normalize(""))
        XCTAssertNil(TextNormalizer.normalize("   \n\t  "))
    }

    func testTruncation() {
        let normalized = TextNormalizer.normalize(String(repeating: "x", count: 20), maxLength: 5)
        XCTAssertEqual(normalized?.text, "xxxxx")
        XCTAssertEqual(normalized?.truncated, true)
    }

    func testNoTruncationFlagWhenFitting() {
        let normalized = TextNormalizer.normalize("short", maxLength: 5)
        XCTAssertEqual(normalized?.truncated, false)
    }
}
final class PastePolicyTests: XCTestCase {
    func testAutoPasteRequiresBothPreferenceAndPermission() {
        XCTAssertTrue(PastePolicy.shouldAutoPaste(autoPasteEnabled: true, accessibilityTrusted: true))
        XCTAssertFalse(PastePolicy.shouldAutoPaste(autoPasteEnabled: true, accessibilityTrusted: false))
        XCTAssertFalse(PastePolicy.shouldAutoPaste(autoPasteEnabled: false, accessibilityTrusted: true))
        XCTAssertFalse(PastePolicy.shouldAutoPaste(autoPasteEnabled: false, accessibilityTrusted: false))
    }

    func testPermissionHintOnlyWhenAutoPasteWantedButNotGranted() {
        XCTAssertTrue(PastePolicy.shouldShowPermissionHint(autoPasteEnabled: true, accessibilityTrusted: false))
        XCTAssertFalse(PastePolicy.shouldShowPermissionHint(autoPasteEnabled: true, accessibilityTrusted: true))
        XCTAssertFalse(PastePolicy.shouldShowPermissionHint(autoPasteEnabled: false, accessibilityTrusted: false))
    }
}

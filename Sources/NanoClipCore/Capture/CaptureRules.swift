import Foundation

/// Everything the capture pipeline needs from one pasteboard change, as plain values so the
/// rules can be unit tested without touching `NSPasteboard`.
public struct PasteboardSnapshot: Sendable, Equatable {
    public var types: Set<String>
    public var string: String?
    /// Image representations, in the source app's own order, untouched.
    public var images: [ImageCandidate]
    public var sourceApp: String?

    public init(
        types: Set<String>,
        string: String? = nil,
        images: [ImageCandidate] = [],
        sourceApp: String? = nil
    ) {
        self.types = types
        self.string = string
        self.images = images
        self.sourceApp = sourceApp
    }
}

public enum SkipReason: String, Sendable, Equatable {
    case concealed
    case transient
    case autoGenerated
    case remoteClipboard
    case filesOnly
    case empty
    case unsupported
    case ignoredApp
    case imagesDisabled
    case imageUnreadable
}

public enum CaptureDecision: Sendable, Equatable {
    case skip(SkipReason)
    case text(text: String, truncated: Bool)
    /// Image data is read lazily by the capture service, so the decision stays value-typed.
    case image
}

public enum CaptureRules {
    static let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType"]
    static let transientTypes: Set<String> = ["org.nspasteboard.TransientType"]
    static let autoGeneratedTypes: Set<String> = ["org.nspasteboard.AutoGeneratedType"]
    static let remoteClipboardTypes: Set<String> = ["com.apple.is-remote-clipboard"]
    public static let fileTypes: Set<String> = [
        "public.file-url",
        "NSFilenamesPboardType",
        "public.file-promise",
        "com.apple.finder.node",
    ]

    public static func decide(_ snapshot: PasteboardSnapshot) -> CaptureDecision {
        if !snapshot.types.isDisjoint(with: concealedTypes) { return .skip(.concealed) }
        if !snapshot.types.isDisjoint(with: transientTypes) { return .skip(.transient) }
        if !snapshot.types.isDisjoint(with: autoGeneratedTypes) { return .skip(.autoGenerated) }
        if !snapshot.types.isDisjoint(with: remoteClipboardTypes) { return .skip(.remoteClipboard) }
        // Files are never recorded: even when a copy also carries a text representation, that text
        // is only the file name, which is noise in a text-history list.
        if !snapshot.types.isDisjoint(with: fileTypes) { return .skip(.filesOnly) }

        if let raw = snapshot.string {
            guard let normalized = TextNormalizer.normalize(raw) else { return .skip(.empty) }
            return .text(text: normalized.text, truncated: normalized.truncated)
        }

        if !snapshot.images.isEmpty { return .image }

        return .skip(.unsupported)
    }
}
